// Pre-optimises photos for the static export (next/image optimisation needs a server).
//
//   assets/photos/<name>.jpg  →  public/images/photos/<name>-<width>.avif|webp
//                             →  data/images.generated.ts (intrinsic sizes for width/height attrs)
//
// Run: npm run images   (re-run after adding or replacing a photo)
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SRC = "assets/photos";
const OUT = "public/images/photos";
const WIDTHS = [480, 640, 800, 1200, 1600];
const HERO_WIDTHS = [...WIDTHS, 2000];

fs.mkdirSync(OUT, { recursive: true });
const manifest = {};

for (const file of fs.readdirSync(SRC).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort()) {
  const name = path.parse(file).name;
  const input = sharp(path.join(SRC, file)).rotate();
  const { width, height } = await input.metadata();
  const widths = (name.startsWith("hero-") ? HERO_WIDTHS : WIDTHS).filter((w) => w <= width);

  for (const w of widths) {
    const resized = input.clone().resize({ width: w });
    const avif = path.join(OUT, `${name}-${w}.avif`);
    const webp = path.join(OUT, `${name}-${w}.webp`);
    if (!fs.existsSync(avif)) await resized.clone().avif({ quality: 50, effort: 4 }).toFile(avif);
    if (!fs.existsSync(webp)) await resized.clone().webp({ quality: 72 }).toFile(webp);
  }
  manifest[name] = { width, height, widths };
  console.log(`${name}: ${width}×${height} → ${widths.join(", ")}`);
}

const ts = `// GENERATED by scripts/optimize-images.mjs — do not edit by hand.
export const photoManifest = ${JSON.stringify(manifest, null, 2)} as const;

export type PhotoName = keyof typeof photoManifest;
`;
fs.writeFileSync("data/images.generated.ts", ts);
